window.PHILOSOPHY.training = {
    currentQuestion: 0,
    correctAnswers: 0,
    questions: [],
    answered: false,

    start() {
        this.currentQuestion = 0;
        this.correctAnswers = 0;
        this.answered = false;

        // Copiar y mezclar las preguntas sin alterar el banco original
        this.questions = [...window.PHILOSOPHY.exercises];

        for (let i = this.questions.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [this.questions[i], this.questions[j]] =
                [this.questions[j], this.questions[i]];
        }

        document.getElementById("training-container").hidden = false;
        document.getElementById("training-results").hidden = true;

        document.getElementById("training-total").textContent =
            this.questions.length;

        this.renderQuestion();
    },

    renderQuestion() {
        const question = this.questions[this.currentQuestion];

        if (!question) return;

        this.answered = false;

        const total = this.questions.length;

        document.getElementById("training-question-number").textContent =
            `PREGUNTA ${this.currentQuestion + 1} DE ${total}`;

        document.getElementById("training-topic").textContent =
            question.topic;

        document.getElementById("training-difficulty").textContent =
            question.difficulty.toUpperCase();

        document.getElementById("training-question").textContent =
            question.question;

        document.getElementById("training-progress-fill").style.width =
            `${((this.currentQuestion + 1) / total) * 100}%`;

        const optionsContainer =
            document.getElementById("training-options");

        optionsContainer.innerHTML = question.options.map((option, index) => `
            <button class="training-option" data-answer="${index}">
                <span class="option-letter">${String.fromCharCode(65 + index)}</span>
                <span>${option}</span>
            </button>
        `).join("");

        document.getElementById("training-feedback").hidden = true;

        const nextButton = document.getElementById("training-next");

        nextButton.disabled = true;
        nextButton.textContent =
            this.currentQuestion === total - 1
                ? "Ver resultados →"
                : "Siguiente pregunta →";

        optionsContainer.querySelectorAll(".training-option").forEach(button => {
            button.addEventListener("click", () => {
                this.checkAnswer(Number(button.dataset.answer));
            });
        });
    },

    checkAnswer(answerIndex) {
        if (this.answered) return;

        this.answered = true;

        const question = this.questions[this.currentQuestion];
        const correct = answerIndex === question.correctAnswer;

        if (correct) this.correctAnswers++;

        window.PHILOSOPHY.progress.registerAnswer(correct);

        document.querySelectorAll(".training-option").forEach(button => {
            const index = Number(button.dataset.answer);

            button.disabled = true;

            if (index === question.correctAnswer) {
                button.classList.add("correct");
            } else if (index === answerIndex) {
                button.classList.add("incorrect");
            }
        });

        const feedback =
            document.getElementById("training-feedback");

        feedback.hidden = false;

        feedback.innerHTML = `
            <strong>${correct ? "¡Respuesta correcta!" : "Respuesta incorrecta"}</strong>
            <p>${question.explanation}</p>
        `;

        document.getElementById("training-next").disabled = false;
    },

    next() {
        if (!this.answered) return;

        if (this.currentQuestion < this.questions.length - 1) {
            this.currentQuestion++;
            this.renderQuestion();
        } else {
            this.showResults();
        }
    },

    showResults() {
        const total = this.questions.length;
        const incorrectAnswers = total - this.correctAnswers;
        const percentage = Math.round(
            (this.correctAnswers / total) * 100
        );

        document.getElementById("training-container").hidden = true;
        document.getElementById("training-results").hidden = false;

        document.getElementById("training-score").textContent =
            `${percentage}%`;

        document.getElementById("training-summary").textContent =
            `Acertaste ${this.correctAnswers} de ${total} preguntas y fallaste ${incorrectAnswers}.`;
    }
};


document.getElementById("training-next").addEventListener("click", () => {
    window.PHILOSOPHY.training.next();
});

document.getElementById("training-restart").addEventListener("click", () => {
    window.PHILOSOPHY.training.start();
});

window.PHILOSOPHY.training.start();
