console.log("Biblioteca filosófica cargada:", window.PHILOSOPHY.lessons.length, "unidades.");

window.PHILOSOPHY.getLesson = function (lessonId) {
    return this.lessons.find(lesson => lesson.id === lessonId);
};

window.PHILOSOPHY.getAllLessons = function () {
    return this.lessons;
};

window.PHILOSOPHY.completeLesson = function (lessonId) {
    const lesson = this.getLesson(lessonId);

    if (!lesson) {
        console.warn("Unidad no encontrada:", lessonId);
        return false;
    }

    this.progress.completeLesson(lessonId);

    console.log("Unidad completada:", lesson.title);

    return true;
};

window.PHILOSOPHY.renderLessons = function () {
    const container = document.getElementById("lessons-container");
    const counter = document.getElementById("library-completed");

    if (!container) return;

    const progress = this.progress;
    const lessons = this.getAllLessons();

    container.innerHTML = lessons.map(lesson => {
        const completed = progress.completedLessons.includes(lesson.id);

        return `
            <article class="lesson-card ${completed ? "completed" : ""}">

                <div class="lesson-card-header">
                    <span class="lesson-number">
                        ${String(lesson.id).padStart(2, "0")}
                    </span>

                    <span class="lesson-category">
                        ${lesson.category}
                    </span>
                </div>

                <div>
                    <h3>${lesson.title}</h3>
                    <p class="lesson-description">
                        ${lesson.description}
                    </p>
                </div>

                <div class="lesson-card-action">
                    <span class="lesson-status">
                        ${completed ? "Unidad completada" : "Pendiente"}
                    </span>

                    <button
                        class="btn btn-outline"
                        data-lesson="${lesson.id}"
                    >
                        ${completed ? "Repasar unidad" : "Comenzar"}
                        →
                    </button>
                </div>

            </article>
        `;
    }).join("");

    if (counter) {
        counter.textContent = progress.completedLessons.length;
    }

    container.querySelectorAll("[data-lesson]").forEach(button => {
        button.addEventListener("click", () => {
            const lessonId = Number(button.dataset.lesson);

            this.openLesson(lessonId);
        });
    });
};

window.PHILOSOPHY.currentLesson = null;

window.PHILOSOPHY.openLesson = function (lessonId) {
    const lesson = this.getLesson(lessonId);

    if (!lesson) return;

    this.currentLesson = lessonId;

    document.getElementById("lessons-container").hidden = true;
    document.getElementById("lesson-viewer").hidden = false;

    document.getElementById("viewer-category").textContent = lesson.category;
    document.getElementById("viewer-number").textContent =
        String(lesson.id).padStart(2, "0");

    document.getElementById("viewer-title").textContent = lesson.title;
    document.getElementById("viewer-subtitle").textContent = lesson.subtitle;

    const topicsContainer = document.getElementById("viewer-topics");


topicsContainer.innerHTML = lesson.content.map((section, index) => `
    <article class="lesson-topic">
        <span class="lesson-topic-number">
            ${String(index + 1).padStart(2, "0")}
        </span>

        <h3>${section.title}</h3>

        ${section.paragraphs.map(paragraph => `
            <p>${paragraph}</p>
        `).join("")}
    </article>
`).join("") + `
    <div class="lesson-key-takeaway">
        <span>PARA RECORDAR</span>
        <p>${lesson.keyTakeaway}</p>
    </div>
`;


    document.getElementById("previous-lesson").disabled = lessonId === 1;
    document.getElementById("next-lesson").disabled =
        lessonId === this.lessons.length;

    document.getElementById("complete-lesson").textContent =
        this.progress.completedLessons.includes(lessonId)
            ? "Unidad completada ✓"
            : "Marcar como completada";

    document.getElementById("lesson-viewer").scrollIntoView({
    behavior: "smooth",
    block: "start"
});
};

window.PHILOSOPHY.closeLesson = function () {
    document.getElementById("lesson-viewer").hidden = true;
    document.getElementById("lessons-container").hidden = false;

    this.currentLesson = null;

    this.renderLessons();
    document.getElementById("library").scrollIntoView({
    behavior: "smooth",
    block: "start"
});
};

window.PHILOSOPHY.changeLesson = function (direction) {
    if (this.currentLesson === null) return;

    const nextId = this.currentLesson + direction;

    if (nextId < 1 || nextId > this.lessons.length) return;

    this.openLesson(nextId);
};
